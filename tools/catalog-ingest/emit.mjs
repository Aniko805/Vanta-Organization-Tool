/**
 * Emit an idempotent official-catalog seed migration.
 * The conflict target matches `part_catalog_official_manufacturer_sku_uidx`
 * from 012_part_catalog_identity.sql. Run that migration first.
 */
import { readdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { catalogRows } from "./normalize.mjs";
import { decodeEntities } from "./parse-product.mjs";
import { activeVendors } from "./vendors.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const dataDir = path.join(here, "data");
const migrationsDir = path.join(repoRoot, "supabase", "migrations");
const monolithicPath = path.join(migrationsDir, "013_seed_official_catalog.sql");

const BATCH_SIZE = 200;
const MAX_PART_CHARS = 180_000;

export function sqlLiteral(value) {
  if (value == null || value === "") return "null";
  // The SQL editor treats `<...>` as markup even inside a quoted value.
  // A span such as `<1400 ... one ... >` is then executed, and `one` is
  // reported as a missing relation. Angle brackets are written out in words.
  const text = decodeEntities(String(value))
    .replace(/\u0000/g, "")
    .replace(/</g, " less than ")
    .replace(/>/g, " greater than ")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
  return `'${text.replace(/'/g, "''")}'`;
}

function insertStatement(rows) {
  const values = rows
    .map((row) => {
      const fields = [
        sqlLiteral(row.name),
        sqlLiteral(row.sku),
        sqlLiteral(row.description),
        sqlLiteral(row.manufacturer),
        "null",
        "true",
        sqlLiteral(row.product_url),
        sqlLiteral(row.image_url),
        sqlLiteral(row.category),
        sqlLiteral(row.source),
      ];
      return `  (${fields.join(", ")})`;
    })
    .join(",\n");
  return `insert into public.part_catalog (
  name,
  sku,
  description,
  manufacturer,
  team_id,
  is_official,
  product_url,
  image_url,
  category,
  source
) values
${values}
on conflict (btrim(manufacturer), btrim(sku))
  where team_id is null
    and is_official
    and sku is not null
do nothing;
`;
}

export function numberOneWords(sql) {
  let count = 0;
  return sql.replace(/\bone\b/gi, () => {
    count += 1;
    return `one(${count})`;
  });
}

export function renderSeedSql(rows, { generatedAt = new Date().toISOString() } = {}) {
  const batches = [];
  for (let index = 0; index < rows.length; index += BATCH_SIZE) {
    batches.push(insertStatement(rows.slice(index, index + BATCH_SIZE)));
  }
  const body = batches.length > 0 ? `\n${batches.join("\n")}\n` : "\n";
  return `-- Generated by tools/catalog-ingest/emit.mjs at ${generatedAt}
-- Idempotent official catalog seed. Applying this file twice does not add rows.
-- Rows: ${rows.length}. No privileged key is used.
-- Requires 012_part_catalog_identity.sql.
${body}`;
}

export function splitSeedParts(rows, { generatedAt = new Date().toISOString(), maxChars = MAX_PART_CHARS } = {}) {
  const statements = [];
  for (let index = 0; index < rows.length; index += BATCH_SIZE) {
    statements.push(insertStatement(rows.slice(index, index + BATCH_SIZE)));
  }
  const groups = [];
  let current = [];
  let size = 0;
  for (const statement of statements) {
    if (current.length > 0 && size + statement.length > maxChars) {
      groups.push(current);
      current = [];
      size = 0;
    }
    current.push(statement);
    size += statement.length;
  }
  if (current.length > 0) groups.push(current);
  return groups.map((group, index) => {
    const part = String(index + 1).padStart(2, "0");
    const rowCount = group.reduce((sum, statement) => sum + (statement.match(/^\s+\(/gm) ?? []).length, 0);
    return {
      name: `013_seed_official_catalog_${part}.sql`,
      sql: numberOneWords(`-- Generated by tools/catalog-ingest/emit.mjs at ${generatedAt}
-- Part ${index + 1} of ${groups.length}. Run 012 first, then these parts in order.
-- Rows in this part: ${rowCount}. Applying a part twice does not add rows.
-- No privileged key is used.
${group.join("\n")}
`),
    };
  });
}

export async function loadCompleteSnapshots() {
  const snapshots = [];
  for (const vendor of Object.values(activeVendors)) {
    const file = path.join(dataDir, `${vendor.id}.json`);
    let snapshot;
    try {
      snapshot = JSON.parse(await readFile(file, "utf8"));
    } catch (error) {
      throw new Error(`Missing snapshot ${file}. Run fetch.mjs ${vendor.id} first.`, { cause: error });
    }
    if (!snapshot.complete) {
      throw new Error(
        `${file} is not a complete crawl (expected ${snapshot.expected_urls ?? "?"} urls, products ${snapshot.products?.length ?? 0}, failures ${snapshot.failures?.length ?? 0}).`,
      );
    }
    snapshots.push(snapshot);
  }
  return snapshots;
}

async function main() {
  const snapshots = await loadCompleteSnapshots();
  const rows = catalogRows(snapshots);
  const parts = splitSeedParts(rows);
  const combined = parts.map((part) => part.sql).join("\n");
  if (/service_role|BEGIN\s+PRIVATE\s+KEY|eyJ[A-Za-z0-9_-]{20,}/.test(combined)) {
    throw new Error("Refusing to write a seed that looks like it contains a secret.");
  }
  const existing = await readdir(migrationsDir);
  await Promise.all(
    existing
      .filter((name) => /^013_seed_official_catalog.*\.sql$/.test(name))
      .map((name) => unlink(path.join(migrationsDir, name))),
  );
  await unlink(monolithicPath).catch((error) => {
    if (error.code !== "ENOENT") throw error;
  });
  for (const part of parts) {
    await writeFile(path.join(migrationsDir, part.name), part.sql, "utf8");
  }
  console.log(`Wrote ${rows.length} rows across ${parts.length} files in ${migrationsDir}`);
}

const isMain = process.argv[1]
  && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
